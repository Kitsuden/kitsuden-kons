#!/usr/bin/env node
/**
 * Writes the kon catalogue of the landing page (site/index.html, between the KONS markers)
 * from each kon's manifest, so the page never lists a kon, a version or a maturity the
 * repository does not have.
 *
 *   node scripts/site.mjs           rewrite the catalogue
 *   node scripts/site.mjs --check   exit 1 if the page is out of date (CI)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const pagePath = join(root, "site", "index.html");
const START = "/* KONS:START (generated by scripts/site.mjs, do not edit by hand) */";
const END = "/* KONS:END */";
const ORDER = { stable: 0, beta: 1, experimental: 2 };

const dirs = readdirSync(join(root, "kons"), { withFileTypes: true })
  .filter((e) => e.isDirectory() && existsSync(join(root, "kons", e.name, "kon.json")))
  .map((e) => e.name);
const inRepo = new Set(dirs);

const kons = dirs
  .map((dir) => {
    const m = JSON.parse(readFileSync(join(root, "kons", dir, "kon.json"), "utf8"));
    const pkg = JSON.parse(readFileSync(join(root, "kons", dir, "package.json"), "utf8"));
    const needs = Array.isArray(m.dependencies?.kons) ? m.dependencies.kons : [];
    return {
      id: m.id.replace(/^kon-/, ""),
      name: m.name,
      description: String(m.description ?? "").replace(/\s+/g, " ").trim(),
      maturity: m.maturity,
      version: pkg.version ?? m.version,
      category: m.category,
      mount: m.mount?.path ?? "",
      tables: (m.tables ?? []).length,
      views: (m.admin?.views ?? []).length,
      // only kons a reader can install from this repository; the core's own are always there
      needs: needs.filter((k) => inRepo.has(k)).map((k) => k.replace(/^kon-/, "")),
    };
  })
  .sort((a, b) => (ORDER[a.maturity] ?? 9) - (ORDER[b.maturity] ?? 9) || a.id.localeCompare(b.id));

const block = `${START}\n      const KONS = ${JSON.stringify(kons)};\n      ${END}`;
const page = readFileSync(pagePath, "utf8");
const from = page.indexOf(START);
const to = page.indexOf(END);
if (from < 0 || to < 0) {
  console.error("site/index.html has no KONS markers");
  process.exit(1);
}
const next = page.slice(0, from) + block + page.slice(to + END.length);

if (process.argv.includes("--check")) {
  if (next !== page) {
    console.error("site/index.html is out of date: run `pnpm site`");
    process.exit(1);
  }
  console.log(`site/index.html lists the ${kons.length} kons of the repository`);
} else {
  writeFileSync(pagePath, next);
  console.log(`site/index.html: ${kons.length} kons`);
}
