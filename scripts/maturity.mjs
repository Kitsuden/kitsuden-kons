#!/usr/bin/env node
/**
 * Writes the kon table of README.md (between the KONS markers) from each kon's
 * manifest: id, maturity, version, SDK, mount path and description.
 *
 *   node scripts/maturity.mjs           rewrite the table
 *   node scripts/maturity.mjs --check   exit 1 if the README is out of date (CI)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const readmePath = join(root, "README.md");
const START = "<!-- KONS:START (generated by scripts/maturity.mjs — do not edit by hand) -->";
const END = "<!-- KONS:END -->";
const EN = { stable: "stable", beta: "beta", experimental: "experimental" };
const ORDER = { stable: 0, beta: 1, experimental: 2 };

function manifest(dir) {
  const kon = join(dir, "kon.json");
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const m = existsSync(kon)
    ? JSON.parse(readFileSync(kon, "utf8"))
    : { id: pkg.kitsuden?.id ?? pkg.name, ...pkg.kitsuden };
  return { ...m, version: pkg.version ?? m.version, description: m.description ?? pkg.description ?? "" };
}

const rows = readdirSync(join(root, "kons"), { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => manifest(join(root, "kons", e.name)))
  .sort((a, b) => (ORDER[a.maturity] ?? 9) - (ORDER[b.maturity] ?? 9) || a.id.localeCompare(b.id));

const oneLine = (s) => String(s).replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
const short = (s) => {
  const t = oneLine(s);
  return t.length > 110 ? `${t.slice(0, 107).trimEnd()}…` : t;
};

/**
 * One table per category, in this order: the repo is a collection of community tools, and a
 * reader looking for a CRM should not have to scroll past the card-game simulators.
 */
const CATEGORIES = [
  ["core", "Core — what most sites install"],
  ["business", "Business"],
  ["content", "Content and community"],
  ["gaming", "Gaming"],
  ["documents", "Documents and OCR"],
];
const header = [
  "| Kon | Maturity | Version | SDK | Mounted at | What it does |",
  "| --- | --- | --- | --- | --- | --- |",
];
const line = (m) =>
  `| \`${m.id}\` | ${EN[m.maturity] ?? "unrated"} | ${m.version ?? ""} | ${m.sdk ?? ""} | \`${m.mount?.path ?? ""}\` | ${short(m.description)} |`;
const uncategorized = rows.filter((m) => !CATEGORIES.some(([c]) => c === m.category));
if (uncategorized.length > 0) {
  console.error(`Kons without a known category: ${uncategorized.map((m) => m.id).join(", ")}`);
  process.exit(1);
}
const table = CATEGORIES.map(([cat, title]) => {
  const inCategory = rows.filter((m) => m.category === cat);
  if (inCategory.length === 0) return "";
  return [`### ${title}`, "", ...header, ...inCategory.map(line)].join("\n");
})
  .filter(Boolean)
  .join("\n\n");

const readme = readFileSync(readmePath, "utf8");
const a = readme.indexOf(START);
const b = readme.indexOf(END);
if (a === -1 || b === -1) {
  console.error("README.md has no KONS markers");
  process.exit(1);
}
const next = `${readme.slice(0, a + START.length)}\n${table}\n${readme.slice(b)}`;

if (process.argv.includes("--check")) {
  if (next !== readme) {
    console.error("README.md kon table is out of date: run `pnpm maturity`.");
    process.exit(1);
  }
  console.log(`README.md kon table is up to date (${rows.length} kons).`);
} else {
  writeFileSync(readmePath, next);
  console.log(`README.md: ${rows.length} kons.`);
}
