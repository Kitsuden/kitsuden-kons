// Re-export router creator (legacy compatibility)
export { createGamesRouter };

// ═══════════════════════════════════════════════════════════════════════════════
// Kon Definition
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * SDK kon (docs/kons/README.md): each route is a declared operation
 * (`gamesOperations`), with its OpenAPI, its MCP tool and its fine-grained scope
 * `kon:games:<operation>`. The router is generated by `defineKonSdk`.
 */
export const kon: KonDefinition = defineKonSdk({
  id: KON_ID,
  name: "Game Library",
  version: manifest.version,
  description:
    "Game library with IGDB integration, collections, screenshots, and trailers. Cover art, screenshots and platform icons are URLs to the core media library (/api/media).",
  icon: "Gamepad2",
  mountPath: "/api/games",
  operations: (ctx: KonContext) => gamesOperations(ctx),

  tables: konTables,

  // kon.json `admin` is the one list of admin views; the definition copies it.
  admin: {
    category: manifest.admin.category as "content",
    views: manifest.admin.views.map((v) => ({
      id: v.id,
      type: v.type as "grid" | "kanban" | "custom",
      title: v.title,
      table: v.table,
    })),
  },

  dependencies: {
    // Cover art and screenshots are ids in the core media library (/api/media), not another kon.
    kons: [],
    core: ["auth"],
  },

  hooks: {
    onStartup: async (ctx) => {
      ctx.logger.info("🎮 Games kon initialized");

      // Verify required tables
      const requiredTables = ["games", "platforms", "tags"];
      const missingTables: string[] = [];

      for (const table of requiredTables) {
        const exists = await ctx.db.tableExists(table);
        if (!exists) {
          missingTables.push(table);
        }
      }

      if (missingTables.length > 0) {
        ctx.logger.warn(`⚠️ Games tables not found: ${missingTables.join(", ")}`);
      } else {
        ctx.logger.info("✅ All games tables verified");
      }
    },

    onEnable: async (ctx) => {
      ctx.logger.info("🎮 Games kon enabled");
    },

    onDisable: async (ctx) => {
      ctx.logger.info("🎮 Games kon disabled");
    },
  },
});

// Default export
export default kon;

// Legacy exports for compatibility
export const gamesModuleRoutes = createKonGames;
