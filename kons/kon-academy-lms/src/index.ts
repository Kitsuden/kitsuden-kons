/** Version and tables come from kon.json, the one place they are written (tests/guards/kon-single-source). */
const konTables = manifest.tables.map((t: string | { name: string }) => (typeof t === "string" ? t : t.name));

/**
 * Definition of the Academy LMS kon: a kon SDK kon (docs/kons/README.md). Each
 * route is a declared operation (`academyOperations`), with its OpenAPI, its
 * MCP tool and its fine-grained scope `kon:academy-lms:<id>`; the router is generated by
 * `defineKonSdk`.
 */
export const kon = defineKonSdk({
  id: KON_ID,
  name: "Academy LMS",
  version: manifest.version,
  description:
    "Complete Learning Management System with courses, modules, quizzes, student progress, assignment groups, Learning Paths, satisfaction surveys, PDF certificates and Excel export.",
  icon: "GraduationCap",

  operations: (ctx: KonContext) => academyOperations(ctx),

  tables: konTables,

  hooks: {
    onEnable: async (ctx) => {
      ctx.logger.info("✅ Academy LMS kon enabled");
    },

    onDisable: async (ctx) => {
      ctx.logger.info("⛔ Academy LMS kon disabled");
    },

    onStartup: async (ctx) => {
      /**
       * Tables are NOT created here. They are created by the kon's migrations.
       *
       * ── WHY IT WAS REMOVED ───────────────────────────────────────────────
       *
       * There was a `runMigrations(ctx)` with twenty-five embedded `CREATE TABLE IF NOT
       * EXISTS`, and it CANNOT work in production: the API connects
       * with a role that has no CREATE privilege on the schema — which is
       * precisely what makes RLS isolation effective.
       *
       * And it failed silently by design. Its `executeSQL` helper caught the
       * error, wrote a log line and returned `false`; nobody looked at that
       * `false`. At real startup twenty-five errors
       * "permission denied for schema public" were visible among hundreds of lines, and the kon
       * considered itself started.
       *
       * All those tables are now created by the files in `migrations/`, which are
       * applied with the admin role, are recorded in
       * `kitsuden_migrations` and fail LOUDLY if something goes wrong.
       *
       * The check below is kept: if the tables are not there, it
       * has to be said. Guarded by `tests/unit/kons-do-not-create-tables.test.ts`.
       */

      const requiredTables = ["courses", "course_modules", "quizzes"];
      const missingTables: string[] = [];

      for (const table of requiredTables) {
        const exists = await ctx.db.tableExists(table);
        if (!exists) {
          missingTables.push(table);
        }
      }

      if (missingTables.length > 0) {
        ctx.logger.warn(`⚠️ Academy tables not found: ${missingTables.join(", ")}`);
      } else {
        ctx.logger.info("📚 Academy tables verified");
      }
    },
  },

  admin: {
    category: "content",
    // The views are kon.json's `admin.views`, the list the admin registry serves; declaring a
    // second list here let the two drift (surveys and certificates were missing). `dashboard` is
    // the registry's alias of `custom`.
    views: manifest.admin.views.map((v) => ({
      id: v.id,
      type: v.type === "dashboard" ? ("custom" as const) : ("grid" as const),
      title: v.title,
      ...("table" in v ? { table: v.table } : {}),
    })),
  },

  dependencies: {
    kons: manifest.dependencies.kons,
    core: [],
  },

  mountPath: "/api/academy",
});

