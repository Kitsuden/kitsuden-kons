/**
 * Round robin persistence — same pattern as the bracket's
 * ============================================================================
 *
 * It reuses the `esports_matches` table: a group set is a set, with its
 * matchday in `round` and its table in `matchOrder`. The engine id (`RR2M1`) goes
 * in `bracketMatchId`, which is the same reconciliation key elimination uses
 * — so the rest of the system (Broadcast included) references group
 * and bracket sets with the same field.
 *
 * Unlike the bracket, the structure is NOT regenerated here with a seed: the
 * schedule is deterministic from the seeding order, so it is
 * rebuilt from the order stored in `tournamentParticipants.seed`.
 */

import type { TournamentRow } from "./bracket.persistence";
import type { EsportsDb } from "./esports.db";
import { tournaments, tournamentParticipants, matches } from "./esports.schema";
import {
  createRoundRobin,
  isRoundRobinComplete,
  reportRoundRobin,
  roundRobinStandings,
  type RoundRobin,
  type RoundRobinReport,
  type RoundRobinStanding,
} from "./roundrobin";

export interface LoadedRoundRobin {
  rr: RoundRobin;
  /** `RR2M1` → row uuid. */
  idByMatchId: Map<string, string>;
}

/** Dumps the schedule into the tournament's rows. */
export async function persistRoundRobin(
  db: EsportsDb,
  tournamentId: string,
  rr: RoundRobin,
  idByMatchId: Map<string, string>
): Promise<void> {
  const { eq } = await import("drizzle-orm");

  const rows = rr.matches.map((m) => ({
    id: idByMatchId.get(m.id)!,
    tournamentId,
    round: m.round,
    matchOrder: m.order,
    bracketMatchId: m.id,
    // A group has no bracket sides; the default value of the
    // enum is left. The tournament's format is what says how to interpret the rows.
    bracketSide: "winners" as const,
    participant1Id: m.participants[0],
    participant2Id: m.participants[1],
    winnerId: m.winnerId,
    participant1Score: m.scores?.[0] ?? 0,
    participant2Score: m.scores?.[1] ?? 0,
    status: toDbStatus(m),
    nextMatchId: null,
    loserNextMatchId: null,
    updatedAt: new Date(),
  }));

  await db.delete(matches).where(eq(matches.tournamentId, tournamentId));
  if (rows.length > 0) {
    await db.insert(matches).values(rows as (typeof matches.$inferInsert)[]);
  }
}

function toDbStatus(m: RoundRobin["matches"][number]) {
  switch (m.status) {
    case "done":
      return "Completed" as const;
    case "bye":
      return "Bye" as const;
    default:
      return "Ready" as const; // in a group, every unplayed set is playable
  }
}

/**
 * Rebuilds the round robin from the rows.
 *
 * The schedule is REGENERATED from the seeding order —it is deterministic— and then
 * the results are reapplied. As with the bracket: rebuilding instead of
 * serializing avoids two representations that could diverge.
 */
export async function loadRoundRobin(
  db: EsportsDb,
  tournament: TournamentRow
): Promise<LoadedRoundRobin> {
  const { eq } = await import("drizzle-orm");

  const parts = await db
    .select()
    .from(tournamentParticipants)
    .where(eq(tournamentParticipants.tournamentId, tournament.id));

  const ordered = [...parts].sort((a, b) => (a.seed ?? 0) - (b.seed ?? 0));
  let rr = createRoundRobin(ordered.map((p) => p.id));

  const rows = await db.select().from(matches).where(eq(matches.tournamentId, tournament.id));

  const idByMatchId = new Map<string, string>();
  for (const r of rows) {
    if (r.bracketMatchId) idByMatchId.set(r.bracketMatchId, r.id);
  }
  for (const m of rr.matches) {
    if (!idByMatchId.has(m.id)) idByMatchId.set(m.id, crypto.randomUUID());
  }

  for (const r of rows) {
    if (r.status !== "Completed" || !r.winnerId || !r.bracketMatchId) continue;
    try {
      rr = reportRoundRobin(rr, r.bracketMatchId, {
        winnerId: r.winnerId,
        scores:
          r.participant1Score || r.participant2Score
            ? [r.participant1Score, r.participant2Score]
            : undefined,
      });
    } catch {
      // A row that no longer fits (group regenerated by hand) is ignored instead
      // of taking the request down; the TO will see the table and can correct.
    }
  }

  return { rr, idByMatchId };
}

export interface AppliedRoundRobinResult {
  rr: RoundRobin;
  standings: RoundRobinStanding[];
  complete: boolean;
}

/**
 * Applies a group result: reread, apply, persist ONLY that row.
 *
 * Unlike the bracket, a group result moves nobody anywhere,
 * so not all the rows have to be rewritten — and overwriting a result to
 * correct it is allowed.
 */
export async function applyRoundRobinResult(
  db: EsportsDb,
  tournament: TournamentRow,
  matchId: string,
  result: RoundRobinReport
): Promise<AppliedRoundRobinResult> {
  const { eq } = await import("drizzle-orm");
  const { rr, idByMatchId } = await loadRoundRobin(db, tournament);

  const next = reportRoundRobin(rr, matchId, result);
  const rowId = idByMatchId.get(matchId);
  const match = next.matches.find((m) => m.id === matchId)!;

  if (rowId) {
    await db
      .update(matches)
      .set({
        winnerId: match.winnerId,
        participant1Score: match.scores?.[0] ?? 0,
        participant2Score: match.scores?.[1] ?? 0,
        status: "Completed",
        updatedAt: new Date(),
      })
      .where(eq(matches.id, rowId));
  }

  const complete = isRoundRobinComplete(next);
  if (complete && tournament.status !== "Completed") {
    await db
      .update(tournaments)
      .set({ status: "Completed", updatedAt: new Date() })
      .where(eq(tournaments.id, tournament.id));
  }

  return { rr: next, standings: roundRobinStandings(next), complete };
}
