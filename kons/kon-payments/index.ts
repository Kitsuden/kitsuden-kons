/** Builds the provider registry; skips those without keys. */
export function buildProviders(env = process.env): Map<string, PaymentProvider> {
  const all = [
    stripeProvider(env),
    lemonSqueezyProvider(env),
    paddleProvider(env),
    paypalProvider(env),
  ];

  const map = new Map<string, PaymentProvider>();
  for (const provider of all) {
    if (provider.isConfigured()) map.set(provider.name, provider);
  }
  return map;
}

/**
 * Bridge to the ledger. Enabled with PAYMENTS_LEDGER=true.
 *
 * It is resolved lazily and tolerantly: if kon-conta is not installed
 * or fails, the payment is recorded anyway — the entry can be reconciled later
 * from the `pay_events` log. Losing a payment over an accounting problem
 * would be far worse than a pending entry.
 */
function makeLedgerBridge(ctx: KonContext) {
  // The ACCOUNTS must be configured: double entry requires knowing which account
  // gets the debit and which the credit, and that depends on each
  // company's chart of accounts. Without them the bridge is not enabled — inventing accounts would produce
  // incorrect accounting, which is worse than having none.
  const debitAccount = process.env.PAYMENTS_LEDGER_DEBIT_ACCOUNT;
  const creditAccount = process.env.PAYMENTS_LEDGER_CREDIT_ACCOUNT;

  return async (event: PaymentEvent, userId: string | null): Promise<string | undefined> => {
    if (process.env.PAYMENTS_LEDGER !== "true") return undefined;
    if (!event.money || event.type === "payment.failed") return undefined;

    if (!debitAccount || !creditAccount) {
      ctx.logger.warn(
        "PAYMENTS_LEDGER is active but the accounts are missing — set " +
          "PAYMENTS_LEDGER_DEBIT_ACCOUNT (bank/gateway) and " +
          "PAYMENTS_LEDGER_CREDIT_ACCOUNT (income)"
      );
      return undefined;
    }

    try {
      // kon-conta is OPTIONAL (only with PAYMENTS_LEDGER=true) and is ANOTHER kon:
      // it is loaded at runtime, as an installed sibling (packages/kons/kon-conta in
      // Kitsuden, kons/kon-conta in kitsuden-kons). The specifier goes in a
      // variable on purpose: with a literal import, type-checking
      // payments required having conta installed, and the image of a deployment that
      // does not use it did not compile. Without conta, the catch below warns about it.
      const contaModule = "../kon-conta/conta.service";
      const { ContaService } = (await import(/* @vite-ignore */ contaModule)) as {
        ContaService: new (db: never) => {
          createJournal(
            input: Record<string, unknown>
          ): Promise<{ journal?: { id?: string } } | null>;
        };
      };
      const conta = new ContaService(ctx.db.instance as never);

      const isRefund = event.type === "payment.refunded";
      const amount = event.money.amount / 100; // cents → monetary unit

      // On a refund the entry is reversed: money goes out and income is cancelled.
      const debit = isRefund ? creditAccount : debitAccount;
      const credit = isRefund ? debitAccount : creditAccount;

      const result = await conta.createJournal({
        date: event.occurredAt.slice(0, 10),
        description: isRefund
          ? `Refund ${event.provider} ${event.externalId}`
          : `Charge ${event.provider} ${event.externalId}`,
        reference: event.externalId,
        // kon-conta has no "outgoing" type: charges go as a
        // standard entry and are distinguished by metadata.source.
        journalType: "standard",
        metadata: {
          source: "kon-payments",
          provider: event.provider,
          userId,
          subscriptionId: event.subscriptionId,
          currency: event.money.currency,
        },
        lines: [
          { accountId: debit, debit: amount, currency: event.money.currency },
          { accountId: credit, credit: amount, currency: event.money.currency },
        ],
      });

      return result?.journal?.id;
    } catch (err) {
      ctx.logger.warn("Could not generate the accounting entry (the payment WAS recorded)", {
        provider: event.provider,
        externalId: event.externalId,
        message: err instanceof Error ? err.message : String(err),
      });
      return undefined;
    }
  };
}

export function createPaymentsKon(ctx: KonContext): Hono {
  const providers = buildProviders();

  if (providers.size === 0) {
    ctx.logger.warn(
      "kon-payments active but no providers configured — " +
        "define STRIPE_SECRET_KEY, LEMONSQUEEZY_API_KEY, PADDLE_API_KEY or PAYPAL_CLIENT_ID"
    );
  }

  return createPaymentsRouter(ctx, providers, makeLedgerBridge(ctx));
}

/**
 * SDK kon (docs/kons/README.md): each route is a declared operation
 * (`paymentsOperations`), with its OpenAPI, its MCP tool and its fine-grained scope.
 *
 * `createRouter` is replaced by the usual one (`createPaymentsKon`): it builds the
 * provider registry and warns if there are none, before mounting the router
 * of the operations.
 */
const definition = defineKonSdk({
  id: KON_ID,
  name: "Payments",
  version: manifest.version,
  description: "Payments and subscriptions: Stripe, Lemon Squeezy, Paddle and PayPal",
  icon: "CreditCard",
  mountPath: "/api/payments",
  operations: (ctx: KonContext) =>
    paymentsOperations(ctx, buildProviders(), makeLedgerBridge(ctx)),

  tables: konTables,

  dependencies: {
    kons: [],
    core: ["auth"],
  },

  hooks: {
    onStartup: async (ctx: KonContext) => {
      const providers = buildProviders();
      const names = Array.from(providers.keys());
      ctx.logger.info(
        names.length > 0
          ? `[Payments] Active providers: ${names.join(", ")}`
          : "[Payments] No providers configured"
      );

      if (process.env.PAYMENTS_LEDGER === "true") {
        ctx.logger.info("[Payments] Accounting bridge ACTIVE → kon-conta");
      }
    },
  },
});

export const kon: KonDefinition = { ...definition, createRouter: createPaymentsKon };

export default kon;
