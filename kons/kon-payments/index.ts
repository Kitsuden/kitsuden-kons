/**
 * Kitsuden Payments — Kon
 * ============================================================================
 *
 * Payments and subscriptions with four providers behind a single interface:
 * Stripe, Lemon Squeezy, Paddle and PayPal.
 *
 * STRATEGY: connect, don't compete. It is not an ecommerce — it is the billing layer
 * that any app needs (the equivalent of Laravel Cashier). Switching
 * gateways does not touch the app's code.
 *
 * THE DIFFERENTIATOR: all providers flow into a single event
 * stream, and that stream can feed `kon-conta`'s ledger. No JS
 * competitor has built-in double-entry bookkeeping — they export a
 * CSV for an accountant to enter. Here the entry is generated by itself.
 *
 * Configuration (only those with keys are activated):
 *   STRIPE_SECRET_KEY / STRIPE_WEBHOOK_SECRET
 *   LEMONSQUEEZY_API_KEY / LEMONSQUEEZY_STORE_ID / LEMONSQUEEZY_WEBHOOK_SECRET
 *   LEMONSQUEEZY_ORDER_VARIANT_ID → a "pay what is asked" variant: lets the shop charge orders here
 *   PADDLE_API_KEY / PADDLE_WEBHOOK_SECRET / PADDLE_ENV
 *   PAYPAL_CLIENT_ID / PAYPAL_CLIENT_SECRET / PAYPAL_WEBHOOK_ID / PAYPAL_ENV
 *   PAYMENTS_LEDGER=true  → generates entries in kon-conta
 *
 * One-time payments for an amount another kon computes (a shop order): `openOrderCheckout`
 * (payments.orders.ts), loaded at runtime by kon-ecommerce. Stripe and Lemon Squeezy implement it.
 */

